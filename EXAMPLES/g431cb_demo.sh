    -F \#endif

# --------------------------------------------------------------------------- #
#  rcc.h  — hand-written G4 clock + PLL + flash configuration.                 #
#  G4 is a single-PLL (F4-style) part: HSE 8 MHz -> PLL (M=2,N=85,R=2) ->     #
#  170 MHz.  Range-1 *boost* mode (PWR_CR5.R1MODE cleared) is required to      #
#  exceed 150 MHz, and the flash needs 4 wait states at 170 MHz.               #
# --------------------------------------------------------------------------- #
create_file "rcc.h" << 'EOF'
#ifndef __RCC_H__
#define __RCC_H__

#include "stm32g431xx.h"

/* The G4 device header does not pull in the generic register-access helpers
 * (they live in the family header stm32g4xx.h, which also drags in the HAL).
 * Define the minimal CMSIS helpers locally, guarded so they are not redefined
 * if a future header provides them. */
#ifndef WRITE_REG
  #define WRITE_REG(REG, VAL)   ((REG) = (VAL))
#endif
#ifndef READ_REG
  #define READ_REG(REG)         ((REG))
#endif
#ifndef MODIFY_REG
  #define MODIFY_REG(REG, CLEARMASK, SETMASK) \
          WRITE_REG((REG), (((READ_REG(REG)) & (~(CLEARMASK))) | (SETMASK)))
#endif
#ifndef SET_BIT
  #define SET_BIT(REG, BIT)     ((REG) |= (BIT))
#endif
#ifndef CLEAR_BIT
  #define CLEAR_BIT(REG, BIT)   ((REG) &= ~(BIT))
#endif

/* G4 @ 170 MHz from an 8 MHz HSE crystal:
 *
 *   HSE            =  8 MHz
 *   PLL input      =  HSE / PLLM(2)       =  4 MHz   (must be 4..16 MHz)
 *   VCO frequency  =  4 MHz * PLLN(85)    = 340 MHz   (must be 128..344 MHz)
 *   PLLR output    = 340 MHz / 2          = 170 MHz   (PLLR field = 0 -> /2; max 170 MHz)
 *
 * The core must run in Voltage Scale 1 *boost* mode (PWR_CR5.R1MODE cleared)
 * to exceed 150 MHz, and the flash needs 4 wait states at 170 MHz.
 */

__STATIC_FORCEINLINE void configure_flash(void) {
  /* Enable the PWR peripheral clock (APB1). */
  RCC->APB1ENR1 |= RCC_APB1ENR1_PWREN;

  /* Voltage Scale 1 (Range 1, highest performance); clear R1MODE to enter
   * boost mode, which is required to run the core above 150 MHz. */
  MODIFY_REG(PWR->CR1, PWR_CR1_VOS, PWR_CR1_VOS_0);
  CLEAR_BIT(PWR->CR5, PWR_CR5_R1MODE);

  /* Flash: 4 wait states + prefetch + instruction/data caches. */
  MODIFY_REG(FLASH->ACR, FLASH_ACR_LATENCY,
             FLASH_ACR_LATENCY_4WS | FLASH_ACR_PRFTEN | FLASH_ACR_ICEN | FLASH_ACR_DCEN);
}

__STATIC_FORCEINLINE void init_rcc(void) {
  configure_flash();

  /* 1. Make sure we are on HSI while reconfiguring the PLL. */
  MODIFY_REG(RCC->CFGR, RCC_CFGR_SW, RCC_CFGR_SW_HSI);
  while ((RCC->CFGR & RCC_CFGR_SWS) != RCC_CFGR_SWS_HSI) {}
  CLEAR_BIT(RCC->CR, RCC_CR_PLLON);
  while (RCC->CR & RCC_CR_PLLRDY) {}

  /* 2. Start the 8 MHz HSE and wait for it to become stable. */
  SET_BIT(RCC->CR, RCC_CR_HSEON);
  while (!(RCC->CR & RCC_CR_HSERDY)) {}

  /* 3. Configure the PLL: source = HSE, M = 2, N = 85, R = 2, enable R output. */
  RCC->PLLCFGR =
      RCC_PLLCFGR_PLLSRC_HSE
    | RCC_PLLCFGR_PLLREN
    | ((2UL - 1UL) << RCC_PLLCFGR_PLLM_Pos)
    | (85UL        << RCC_PLLCFGR_PLLN_Pos)
    | (0UL        << RCC_PLLCFGR_PLLR_Pos);

  /* 4. Enable the PLL and wait for lock. */
  SET_BIT(RCC->CR, RCC_CR_PLLON);
  while (!(RCC->CR & RCC_CR_PLLRDY)) {}

  /* 5. Bus prescalers: AHB = /1, APB1 = /2, APB2 = /2. */
  RCC->CFGR |= RCC_CFGR_HPRE_DIV1 | RCC_CFGR_PPRE1_DIV2 | RCC_CFGR_PPRE2_DIV2;

  /* 6. Switch the system clock to the PLL output. */
  MODIFY_REG(RCC->CFGR, RCC_CFGR_SW, RCC_CFGR_SW_PLL);
  while ((RCC->CFGR & RCC_CFGR_SWS) != RCC_CFGR_SWS_PLL) {}

  /* Enable the GPIOC clock (LED on PC6) before init_gpio() configures pins. */
  RCC->AHB2ENR |= RCC_AHB2ENR_GPIOCEN;

  /* PLL output verified at 170 MHz for this board. */
  SystemCoreClock = 170000000u;
}

#endif /* __RCC_H__ */
EOF

# --------------------------------------------------------------------------- #
#  gpio.h  — generated by stm32cgen.  G4 register bit naming (GPIO_MODER_MODE  #
#  and GPIO_OSPEEDR_OSPEED) is used; PC6 is the LED output.                    #
# --------------------------------------------------------------------------- #
generate_header "gpio.h" -l g431cb -p GPIOC -m gpio -f init_gpio\
    --exclude-register IDR LCKR\
    -D USE_ANALOG_MODE_FOR_ALL_PINS_BY_DEFAULT 1\
       ""\
       GPIO_MODE "(USE_ANALOG_MODE_FOR_ALL_PINS_BY_DEFAULT * UINT32_MAX)"\
       PIN_XOR "(GPIO_MODE & 3UL)"\
       ""\
       PIN_MODE_INPUT "(0x00UL ^ PIN_XOR)"\
       PIN_MODE_OUTPUT "(0x01UL ^ PIN_XOR)"\
       PIN_MODE_AF "(0x02UL ^ PIN_XOR)"\
       PIN_MODE_ANALOG "(0x03UL ^ PIN_XOR)"\
       ""\
       "PIN_CFG(PIN, MODE)" "((MODE)   << ((PIN) * 2))"\
       "PIN_MODE(PIN, MODE)" "(((MODE)  << GPIO_MODER_MODE ## PIN ## _Pos) & GPIO_MODER_MODE ## PIN ## _Msk)"\
       "PIN_SPEED(PIN, SPEED)" "(((SPEED) << GPIO_OSPEEDR_OSPEED ## PIN ## _Pos) & GPIO_OSPEEDR_OSPEED ## PIN ## _Msk)"\
       "PIN_OTYPE(PIN, OTYPE)" "((OTYPE)   ? GPIO_OTYPER_OT ## PIN : 0)"\
       "PIN_PUPD(PIN, PUPD)" "(((PUPD)  << GPIO_PUPDR_PUPD ## PIN ## _Pos) & GPIO_PUPDR_PUPD ## PIN ## _Msk)"\
       "PIN_AF(PIN, AF)" "(AF << (PIN * 4))"\
       ""\
       GPIOC_MODE "( PIN_MODE(6, PIN_MODE_OUTPUT) /* PC6 -- LED */ )"\
       GPIOC_OTYPE "( 0 )"\
       GPIOC_OSPEED "( PIN_SPEED(6, PIN_SPEED_HIGH) /* PC6 -- high speed */ )"\
       GPIOC_PUPD "( 0 )"\
       ""\
       GPIOC_MODER "(GPIO_MODE ^ (GPIOC_MODE))"\
       GPIOC_OTYPER "(GPIOC_OTYPE)"\
       GPIOC_OSPEEDR "(GPIOC_OSPEED)"\
       GPIOC_PUPDR "(GPIOC_PUPD)"\
    \
    $force_inline\
    --no-def

cd ..

# Create main.c file in src directory from embedded data using Here Document
main_c_file="${directories[1]}/main.c"
if [ ! -f "$main_c_file" ]; then
  op_counter=$((op_counter + 1))
  cat << 'EOF' > "$main_c_file"
#include "main.h"

/* WeAct Studio STM32G431CBU6: a green LED is wired to PC6 (active HIGH).
 * The loop below blinks it at ~1 Hz using bit 9 of the 1 ms uptime counter
 * (same scheme as the F1/F4 reference demos: bit 9 flips every 512 ms, so the
 * LED period is 1024 ms ~= 1 Hz). */

static volatile uint64_t g_ticks;

void SysTick_Handler(void) {
  g_ticks++;
}

uint64_t uptime(void) {
  return g_ticks;
}

int main(void) {
  /* init() performs: init_rcc() -> init_gpio() -> init_systick(). */
  for (init(); process(); idle());
}

unsigned process(void) {
  /* Blink at ~1 Hz: bit 9 of the 1 ms uptime counter toggles every 512 ms,
   * so the LED is on for 512 ms and off for 512 ms (period ~1024 ms). */
  if (uptime() & (1ULL << 9)) {
    GPIOC->BSRR = GPIO_BSRR_BS6;       /* PC6 high -> LED on  */
  } else {
    GPIOC->BSRR = GPIO_BSRR_BR6;       /* PC6 low  -> LED off */
  }

  return !0;  /* Always continue loop */
}

void idle(void) {
  __WFI();
}
EOF
  echo "File $main_c_file created."
fi

