## Clock — 170 MHz

The G431 is a Cortex-M4F part rated up to **170 MHz**. `main.h` sets
`HCLK = 170`; `rcc.h` implements:

| Stage        | Value      | Result                |
|--------------|------------|-----------------------|
| HSE          | 8 MHz      | WeAct-style G431 crystal |
| PLLM         | 2          | VCO in = 4 MHz        |
| PLLN         | 85         | VCO = 340 MHz         |
| PLLR         | 2          | PLL = 170 MHz          |
| AHB (HPRE)   | /1         | HCLK = 170 MHz        |
| APB1 (PPRE1) | /2         | PCLK1 = 85 MHz        |
| APB2 (PPRE2) | /2         | PCLK2 = 85 MHz        |

### Verified 170 MHz

`configure_flash()` performs the correct G4 power sequence before the clock
switch: it enables the PWR clock, selects **regulator Range 1** and **clears
`PWR_CR5.R1MODE`** (boost mode, required to run the core above 150 MHz), then
programs the flash with **4 wait states** plus prefetch and both caches. The PLL
factor bits in `rcc.h` are written directly for the 170 MHz target. `init_rcc()`
stores `SystemCoreClock = 170000000u`, which the 1 ms SysTick in `main.h` uses.

> Note: the G4 is a single-PLL part (like the F4), so the clock tree is
> `HSE -> PLL (M/N/R) -> SYSCLK`. Unlike the G0, the GPIO banks live on
> `AHB2` and the flash needs wait states even at low frequencies.

