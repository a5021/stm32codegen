## Configuration knobs

The main tunables live at the top of `inc/main.h`:

| Macro                 | Default | Meaning                          |
|-----------------------|---------|----------------------------------|
| `HCLK`                | `170`   | System clock in MHz (8-170)      |
| `SYSTICK_CLOCK_SOURCE`| `0`     | 0 = HCLK/8, 1 = HCLK             |
| `SYSTICK_ENABLE`      | `YES`   | enable SysTick                   |
| `SYSTICK_IRQ_ENABLE`  | `YES`   | IRQ vs polling mode              |

To change the LED pin, edit the `GPIOC_MODE` define in `inc/gpio.h` (or the
`stm32cgen` invocation in the `.sh` script); the `GPIOC` clock-enable bit is
handled by `rcc.h`.

