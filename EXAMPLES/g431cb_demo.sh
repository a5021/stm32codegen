## What the script does

`g431cb_demo.sh` is a self-contained project generator. Running it:

1. Creates the directory tree (`inc/`, `src/`, `MDK-ARM/`).
2. Generates the CMSIS-based configuration headers with `stm32cgen`:
   - `inc/main.h` — top-level config (clock, SysTick, init order) and the
     `init()` sequence (`init_rcc` -> `init_gpio` -> `init_systick`).
   - `inc/gpio.h` — `init_gpio()` configuring PC6 as a high-speed output using
     the G4 register bit naming (`GPIO_MODER_MODE*`, `GPIO_OSPEEDR_OSPEED*`).
   - `inc/rcc.h` — `init_rcc()` / `configure_flash()`: the PLL factor bits are
     wired directly for 170 MHz, with the correct G4 voltage-scaling sequence.
3. Writes `src/main.c` (PC6 blink off a 1 ms SysTick time base), the linker
   script, the Makefile and the debugger/IDE configurations.
4. Downloads the vendor CMSIS files (device header, startup, system init) and
   the SVD description from upstream sources (cached for re-runs).
5. Builds the project with `make debug` to verify everything is consistent.

All downloaded files are cached — re-running the script skips what already
exists and only rebuilds.

