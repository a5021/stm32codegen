# STM32G431CB Demo

Bare-metal example for the **STM32G431CBU6** (WeAct Studio STM32G431 Core Board),
generated by `g431cb_demo.sh`. It demonstrates a **170 MHz** clock (the rated
maximum for the G4, a Cortex-M4F part) and a simple **LED** blink on **PC6**
(active HIGH) — all using only CMSIS, no HAL.

The example reuses the best practices of the other demos: `stm32cgen` produces
`main.h` (clock + SysTick + init order) and `gpio.h` (PC6 output), while `rcc.h`
is a hand-written, header-only G4 clock/PLL/flash configuration.

